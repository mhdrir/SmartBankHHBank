package com.smartbank.payments.api;

import com.smartbank.payments.api.dto.CreatePaymentRequest;
import com.smartbank.payments.api.dto.PaymentResponse;
import com.smartbank.payments.application.PaymentService;
import com.smartbank.payments.application.PaymentService.CreationResult;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import jakarta.validation.Valid;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Size;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestHeader;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;
import org.springframework.web.servlet.support.ServletUriComponentsBuilder;

import java.net.URI;
import java.util.UUID;

/**
 * REST API for credit transfers.
 *
 * Design decisions:
 *  - Versioned path (/api/v1): breaking changes go to /v2 while /v1 keeps working for clients.
 *  - POST returns 202 ACCEPTED (not 201): processing is asynchronous. The client gets a Location
 *    header and polls GET /payments/{id} (or listens to events) for the final status.
 *  - Idempotency-Key header is REQUIRED: networks fail, clients retry; a retry must never move
 *    money twice. Replay of the same key returns 200 with the existing payment.
 *  - The controller only translates HTTP <-> application; no business logic here.
 */
@RestController
@RequestMapping("/api/v1/payments")
// No @Validated on the class: since Spring 6.1, MVC validates constrained parameters (@NotBlank on the
// header) itself and returns 400 via HandlerMethodValidationException. Adding @Validated would
// validate twice (AOP + MVC).
public class PaymentController {

    private final PaymentService paymentService;

    public PaymentController(PaymentService paymentService) {
        this.paymentService = paymentService;
    }

    @Operation(summary = "Initiate a credit transfer (asynchronous)")
    @PostMapping
    public ResponseEntity<PaymentResponse> create(
            @Parameter(description = "Unique per payment, e.g. a UUID generated by the client")
            @RequestHeader("Idempotency-Key") @NotBlank @Size(max = 100) String idempotencyKey,
            @Valid @RequestBody CreatePaymentRequest request) {

        CreationResult result = paymentService.createPayment(idempotencyKey, request.toCommand());
        PaymentResponse body = PaymentResponse.from(result.payment());

        if (result.replayed()) {
            return ResponseEntity.ok(body);
        }
        URI location = ServletUriComponentsBuilder.fromCurrentRequest()
                .path("/{id}").buildAndExpand(body.id()).toUri();
        return ResponseEntity.accepted().location(location).body(body);
    }

    @Operation(summary = "Get a payment and its current status")
    @GetMapping("/{id}")
    public PaymentResponse get(@PathVariable UUID id) {
        return PaymentResponse.from(paymentService.getPayment(id));
    }
}
